func appSpec(app, pkg string) string {
	return `(project notes (module example.com/notes) (go 1.22)
  (require (uuid github.com/google/uuid v1.6.0))
  ` + app + `
  (package notes ` + pkg + `))`
}

func genApp(t *testing.T, out, spec string) error {
	t.Helper()
	sp, _ := writeSpec(t, t.TempDir(), spec, "")
	return run(Options{Spec: sp, Out: out, Reselect: true}, io.Discard)
}

const notesPkg = `(entity Note (field ID string) (field Text string) (store get list save))
    (events (event NoteSaved (field ID string)))
    (api (get Note) (save Note))`

func TestAppWiresWhatTheRunProduced(t *testing.T) {
	out := t.TempDir()
	if err := genApp(t, out, appSpec("(app)", notesPkg)); err != nil {
		t.Fatal(err)
	}
	wire := read(t, out, "cmd/notes/wire_gen.go")
	for _, want := range []string{
		"// Code generated by tilegen. DO NOT EDIT.",
		"// Nothing: every part of this program is built from the others.",
		"\tNoteStore notes.NoteStore\n", "\tBus       notes.Bus\n", "\tHandler   *notes.Handler\n", // held as what they are used as
		"a.NoteStore = notes.NewMemoryNoteStore()",
		"a.Handler = notes.NewHandler(a.NoteStore)",
		`mux.Handle("/", a.Handler.Routes())`,
	} {
		if !strings.Contains(wire, want) {
			t.Errorf("wire_gen.go missing %q:\n%s", want, wire)
		}
	}
	// A part is built after what it is built from.
	if strings.Index(wire, "notes.NewMemoryNoteStore()") > strings.Index(wire, "notes.NewHandler(") {
		t.Error("the store must be built before the handler that takes it")
	}
	for _, f := range []string{"cmd/notes/wire_gen.go", "cmd/notes/main.go"} {
		if _, err := parser.ParseFile(token.NewFileSet(), f, read(t, out, f), 0); err != nil {
			t.Errorf("%s does not parse: %v", f, err)
		}
	}

	// main.go is the caller's: a second run leaves an edit alone.
	mainPath := filepath.Join(out, "cmd/notes/main.go")
	edited := read(t, out, "cmd/notes/main.go") + "\n// mine\n"
	if err := os.WriteFile(mainPath, []byte(edited), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := genApp(t, out, appSpec("(app)", notesPkg)); err != nil {
		t.Fatal(err)
	}
	if read(t, out, "cmd/notes/main.go") != edited {
		t.Error("main.go was overwritten")
	}
	if read(t, out, "cmd/notes/wire_gen.go") != wire {
		t.Error("generating twice changed the wiring")
	}

	// No (app), no program: the wiring goes, main.go stays the caller's.
	if err := genApp(t, out, appSpec("", notesPkg)); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(out, "cmd/notes/wire_gen.go")); err == nil {
		t.Error("wire_gen.go should be swept once the spec has no (app)")
	}
}

func TestAppAsksForWhatNothingSupplies(t *testing.T) {
	out := t.TempDir()
	pkg := `(entity Order (field ID uuid.UUID) (store get save (durable) (cross-process)))
    (events (cross-process) (event OrderPlaced (field OrderID uuid.UUID)) (outbox Order))
    (api (get Order) (watch OrderPlaced) (grpc-native))
    (secrets (secret DatabaseURL) (audited))`
	if err := genApp(t, out, appSpec("(app notesd)", pkg)); err != nil {
		t.Fatal(err)
	}
	wire := read(t, out, "cmd/notesd/wire_gen.go")
	for _, want := range []string{
		// One pool serves both constructors that ask for it.
		"NotesOutboxDB", "notes.OutboxDB // for notes.NewOutbox, notes.NewOutboxRelay",
		"*db.Queries", "// for notes.NewPostgresOrderStore",
		"*nats.Conn", `nats "github.com/nats-io/nats.go"`,
		// A setting belongs to the constructor that asked; a client is shared by name.
		"VaultClient", "NotesVaultSecretsMount string", "NotesVaultSecretsTtl", "time.Duration",
		`out = append(out, "Queries (*db.Queries)")`,
		`return nil, errors.New("not set in Deps: " + strings.Join(m, ", "))`,
		// The bus the API streams from is the one the relay publishes to.
		"a.APIServer = notes.NewAPIServer(a.OrderStore, a.Bus)",
		"a.OutboxRelay = notes.NewOutboxRelay(d.NotesOutboxDB, a.Bus)",
		// A constructor that can fail stops the build; one that takes a context gets it.
		"if a.Secrets, err = notes.NewVaultSecrets(ctx, d.VaultClient,", `return nil, fmt.Errorf("notes.NewVaultSecrets: %w", err)`,
		// What runs is run, what registers is registered.
		"a.OutboxRelay.Run(ctx, func(err error)", "a.APIServer.Register(gs)", `os.Getenv("GRPC_ADDR")`,
	} {
		if !strings.Contains(wire, want) {
			t.Errorf("wire_gen.go missing %q:\n%s", want, wire)
		}
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "wire_gen.go", wire, 0); err != nil {
		t.Errorf("does not parse: %v", err)
	}
	main := read(t, out, "cmd/notesd/main.go")
	if !strings.Contains(main, "// d.Queries = ...   *db.Queries, for notes.NewPostgresOrderStore") {
		t.Errorf("main.go should list what deps has to open:\n%s", main)
	}
}

func TestAppFollowsAnEditedConstructor(t *testing.T) {
	// The wiring is read back from the Go, so a constructor changed by hand
	// in a scaffolded file is wired as it now is.
	out := t.TempDir()
	if err := genApp(t, out, appSpec("(app)", notesPkg)); err != nil {
		t.Fatal(err)
	}
	store := filepath.Join(out, "notes/memory_note_store.go")
	src := strings.Replace(read(t, out, "notes/memory_note_store.go"),
		"func NewMemoryNoteStore() *MemoryNoteStore {", "func NewMemoryNoteStore(capacity int) *MemoryNoteStore {", 1)
	if err := os.WriteFile(store, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := genApp(t, out, appSpec("(app)", notesPkg)); err != nil {
		t.Fatal(err)
	}
	wire := read(t, out, "cmd/notes/wire_gen.go")
	if !strings.Contains(wire, "NotesMemoryNoteStoreCapacity int") || !strings.Contains(wire, "notes.NewMemoryNoteStore(d.NotesMemoryNoteStoreCapacity)") {
		t.Errorf("the new parameter should become a field of Deps:\n%s", wire)
	}

	// Two things that could be the NoteStore: say so, rather than pick.
	more := src + "\ntype OtherStore struct{ MemoryNoteStore }\n\nfunc NewOtherStore() *OtherStore { return &OtherStore{} }\n\nvar _ NoteStore = (*OtherStore)(nil)\n"
	if err := os.WriteFile(store, []byte(more), 0o644); err != nil {
		t.Fatal(err)
	}
	err := genApp(t, out, appSpec("(app)", notesPkg))
	if err == nil || !strings.Contains(err.Error(), "notes.NewMemoryNoteStore and notes.NewOtherStore both supply notes.NoteStore") {
		t.Errorf("want the ambiguity named, got: %v", err)
	}
}

func TestAppErrors(t *testing.T) {
	for app, want := range map[string]string{
		"(app Notes)": "expected (app) or (app name)",
		"(app a b)":   "expected (app) or (app name)",
		"(app (x))":   "expected (app) or (app name)",
	} {
		if err := genApp(t, t.TempDir(), appSpec(app, notesPkg)); err == nil || !strings.Contains(err.Error(), want) {
			t.Errorf("%s: want %q, got %v", app, want, err)
		}
	}
}
